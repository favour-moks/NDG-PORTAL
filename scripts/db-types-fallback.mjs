// Regenerates src/types/database.ts via direct information_schema
// introspection — a fallback for `npm run db:types`, which needs Docker
// (for `supabase gen types --db-url`) or a personal access token (for
// --project-id), neither of which has been available in this environment.
// Needs the `pg` package, which is NOT a project dependency (this script
// is the only thing that uses it) — install it first:
//   npm install --no-save pg
//   node --env-file=.env.local scripts/db-types-fallback.mjs
//   npm uninstall pg --no-save
// See docs/infrastructure.md. Prefer `npm run db:types` once Docker or a
// PAT is available — this fallback doesn't know about custom Postgres
// functions/enums and reconstructs the shape from columns alone.
import pg from 'pg'
import { writeFileSync } from 'node:fs'

const client = new pg.Client({ connectionString: process.env.DATABASE_URL })
await client.connect()

const { rows: columns } = await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable,
         c.column_default, t.table_type
  from information_schema.columns c
  join information_schema.tables t
    on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public'
  order by c.table_name, c.ordinal_position
`)

await client.end()

function tsType(col) {
  const udt = col.udt_name
  if (udt.startsWith('_')) {
    const inner = tsType({ ...col, udt_name: udt.slice(1) })
    return `${inner}[]`
  }
  switch (udt) {
    case 'uuid':
    case 'text':
    case 'varchar':
    case 'bpchar':
    case 'timestamptz':
    case 'timestamp':
    case 'date':
    case 'bytea':
    case 'inet':
      return 'string'
    case 'bool':
      return 'boolean'
    case 'int2':
    case 'int4':
    case 'int8':
    case 'numeric':
    case 'float4':
    case 'float8':
      return 'number'
    case 'jsonb':
    case 'json':
      return 'Json'
    default:
      return 'string'
  }
}

const byTable = new Map()
for (const col of columns) {
  if (!byTable.has(col.table_name)) byTable.set(col.table_name, { type: col.table_type, columns: [] })
  byTable.get(col.table_name).columns.push(col)
}

function rowType(cols) {
  return cols
    .map((c) => `          ${JSON.stringify(c.column_name)}: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`)
    .join('\n')
}

function insertType(cols) {
  return cols
    .map((c) => {
      const optional = c.is_nullable === 'YES' || c.column_default !== null
      return `          ${JSON.stringify(c.column_name)}${optional ? '?' : ''}: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`
    })
    .join('\n')
}

function updateType(cols) {
  return cols
    .map((c) => `          ${JSON.stringify(c.column_name)}?: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`)
    .join('\n')
}

const tableEntries = []
const viewEntries = []

for (const [name, { type, columns: cols }] of byTable) {
  if (type === 'VIEW') {
    viewEntries.push(`      ${JSON.stringify(name)}: {
        Row: {
${rowType(cols)}
        }
        Relationships: []
      }`)
  } else {
    tableEntries.push(`      ${JSON.stringify(name)}: {
        Row: {
${rowType(cols)}
        }
        Insert: {
${insertType(cols)}
        }
        Update: {
${updateType(cols)}
        }
        Relationships: []
      }`)
  }
}

const output = `// Generated by scripts/db-types-fallback.mjs via direct information_schema
// introspection (Docker and a Supabase personal access token were both
// unavailable in the environment that generated this). Regenerate with
// \`npm run db:types\` once either is available — see docs/infrastructure.md.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type Database = {
  public: {
    Tables: {
${tableEntries.join('\n')}
    }
    Views: {
${viewEntries.join('\n')}
    }
    Functions: {
      [key: string]: never
    }
    Enums: {
      [key: string]: never
    }
    CompositeTypes: {
      [key: string]: never
    }
  }
}
`

writeFileSync('src/types/database.ts', output)
console.log(`Wrote src/types/database.ts (${byTable.size} relations)`)
